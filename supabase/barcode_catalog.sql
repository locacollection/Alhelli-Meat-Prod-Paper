do $$
declare bad_count integer; row_count integer; confirmed_count integer;
begin
  with examples(item_code,weight_grams,ean13) as (
    values
    ('6777',5,'9667778000154'),('6777',100,'9667771003206'),
    ('6777',300,'9667775009556'),('6777',400,'9667777012752'),
    ('6777',500,'9667776015952'),('6777',505,'9667778016100'),
    ('6777',1000,'9667770031903'),('6777',1410,'9667772045007'),
    ('6777',2000,'9667779063806'),('6777',2775,'9667777088504'),
    ('6777',5000,'9667774159504'),('6777',5780,'9667770184401'),
    ('6780',505,'9667800022758'),('6780',1000,'9667802045007'),
    ('6781',1000,'9667812045004')
  )
  select count(*) into bad_count from examples e
  left join public.meat_barcode_catalog c
    on c.item_code=e.item_code and c.weight_grams=e.weight_grams
  where c.ean13 is distinct from e.ean13;
  select count(*) into row_count from public.meat_barcode_catalog;
  select count(*) into confirmed_count from public.meat_barcode_catalog where label_verified;
  if bad_count <> 0 or row_count <> 6000 or confirmed_count <> 15 then
    raise exception 'Barcode catalog validation failed: mismatches %, total %, label-verified %',
      bad_count,row_count,confirmed_count;
  end if;
end;
$$;

