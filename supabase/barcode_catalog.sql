-- Alhelli Meat Production: 3-product price-encoded EAN-13 barcode catalog
-- Initial prices: 6777 = 3190 fils/kg; 6780 and 6781 = 4500 fils/kg.
-- Units: 5 gram steps, 5-fils price rounding, weight 5 to 10000 grams.
-- Every generated number has a valid EAN-13 final check digit.
-- The seventh digit uses GS1 section 7.9.4 five-digit price verifier.
-- GENERATED rows are NOT proof of acceptance by the supermarket POS/scale.

create schema if not exists private;

create or replace function private.meat_price_verifier_5(price_fils integer)
returns integer language plpgsql immutable strict
set search_path = pg_catalog as $$
declare
  digits text;
  total integer := 0;
  i integer;
  d integer;
  remainder integer;
  five_plus constant integer[] := array[0,5,1,6,2,7,3,8,4,9];
  two_minus constant integer[] := array[0,2,4,6,8,9,1,3,5,7];
  five_minus constant integer[] := array[0,5,9,4,8,3,7,2,6,1];
  inverse_five_minus constant integer[] := array[0,9,7,5,3,1,8,6,4,2];
begin
  if price_fils < 0 or price_fils > 99999 then
    raise exception 'Price % cannot be encoded as a five-digit price field', price_fils;
  end if;
  digits := lpad(price_fils::text,5,'0');
  for i in 1..5 loop
    d := substring(digits from i for 1)::integer;
    case i
      when 1 then total := total + five_plus[d+1];
      when 2 then total := total + two_minus[d+1];
      when 3 then total := total + five_minus[d+1];
      when 4 then total := total + five_plus[d+1];
      when 5 then total := total + two_minus[d+1];
    end case;
  end loop;
  remainder := (10 - (total % 10)) % 10;
  return inverse_five_minus[remainder+1];
end;
$$;

create or replace function private.meat_ean13_check_digit(first_12 text)
returns integer language plpgsql immutable strict
set search_path = pg_catalog as $$
declare
  i integer;
  total integer := 0;
begin
  if length(first_12) <> 12 or first_12 !~ '^[0-9]{12}$' then
    raise exception 'EAN-13 requires exactly 12 digits before its check digit';
  end if;
  for i in 1..12 loop
    total := total + substring(first_12 from i for 1)::integer *
      (case when i % 2 = 0 then 3 else 1 end);
  end loop;
  return (10 - (total % 10)) % 10;
end;
$$;

create table if not exists public.meat_barcode_products (
  item_code text primary key check (item_code in ('6777','6780','6781')),
  product_name text not null,
  barcode_prefix text not null unique check (barcode_prefix ~ '^[0-9]{6}$'),
  unit_price_fils_per_kg integer not null check (unit_price_fils_per_kg > 0),
  updated_at timestamptz not null default now()
);

insert into public.meat_barcode_products
  (item_code,product_name,barcode_prefix,unit_price_fils_per_kg)
values
  ('6777','Pakistani Beef With Bone','966777',3190),
  ('6780','Pakistani Beef Minced','966780',4500),
  ('6781','Pakistani Beef Without Bone','966781',4500)
on conflict (item_code) do update set
  product_name=excluded.product_name,
  barcode_prefix=excluded.barcode_prefix,
  unit_price_fils_per_kg=excluded.unit_price_fils_per_kg,
  updated_at=now();

create table if not exists public.meat_barcode_catalog (
  id bigint generated by default as identity primary key,
  item_code text not null references public.meat_barcode_products(item_code),
  product_name text not null,
  barcode_prefix text not null check (barcode_prefix ~ '^[0-9]{6}$'),
  weight_grams integer not null check (weight_grams between 5 and 10000 and weight_grams % 5 = 0),
  unit_price_fils_per_kg integer not null,
  total_price_fils integer not null check (total_price_fils between 0 and 99999 and total_price_fils % 5 = 0),
  price_verifier_digit smallint not null check (price_verifier_digit between 0 and 9),
  ean13 text not null unique check (ean13 ~ '^[0-9]{13}$'),
  label_verified boolean not null default false,
  updated_at timestamptz not null default now(),
  unique(item_code,weight_grams)
);

create index if not exists meat_barcode_catalog_weight_idx
 on public.meat_barcode_catalog (weight_grams);

with priced as (
  select p.item_code,p.product_name,p.barcode_prefix,p.unit_price_fils_per_kg,
         grams.weight_grams,
         (((grams.weight_grams * p.unit_price_fils_per_kg + 2500) / 5000) * 5)::integer as total_price_fils
  from public.meat_barcode_products as p
  cross join lateral generate_series(5,10000,5) as grams(weight_grams)
), verified as (
  select *,private.meat_price_verifier_5(total_price_fils) as price_verifier_digit
  from priced
), encoded as (
  select *,
    (barcode_prefix || price_verifier_digit::text || lpad(total_price_fils::text,5,'0')) as first_12
  from verified
)
insert into public.meat_barcode_catalog
  (item_code,product_name,barcode_prefix,weight_grams,unit_price_fils_per_kg,
   total_price_fils,price_verifier_digit,ean13,label_verified)
select item_code,product_name,barcode_prefix,weight_grams,unit_price_fils_per_kg,
       total_price_fils,price_verifier_digit,
       first_12 || private.meat_ean13_check_digit(first_12)::text,false
from encoded
on conflict (item_code,weight_grams) do update set
 product_name=excluded.product_name,
 barcode_prefix=excluded.barcode_prefix,
 unit_price_fils_per_kg=excluded.unit_price_fils_per_kg,
 total_price_fils=excluded.total_price_fils,
 price_verifier_digit=excluded.price_verifier_digit,
 ean13=excluded.ean13,
 label_verified=false,
 updated_at=now();

-- Manually confirmed printed-label examples from the conversation.
